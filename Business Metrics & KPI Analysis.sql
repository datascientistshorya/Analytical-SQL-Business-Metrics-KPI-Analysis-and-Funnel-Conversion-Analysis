/*Q1 — Total Revenue
Calculate total revenue from completed orders.
Return:
•	total_revenue */
select sum(amount) as completed_orders_revenuee from orders
where status ='Completed';

/*Q2 — Total Orders & Completed Orders
Calculate:
•	total number of orders 
•	number of completed orders 
•	number of cancelled orders 
Return:
•	total_orders 
•	completed_orders 
•	cancelled_orders*/

with order_data as(
	select count(*) as total_orders,
	
    sum(case when status='Completed' then 1 else 0 end) as completed_orders,
    sum(case when status='Cancelled' then 1 else 0 end) as cancelled_orders
	from orders
)
select* from order_data;

/*Q3 — Average Order Value
Calculate the Average Order Value (AOV) for completed orders.
Return:
•	aov */
with order_data as(
	select count(*) as total_orders,
	sum(case when status='Completed' then amount else 0 end) as completed_rev
    from orders
)
select completed_rev/total_orders as AOV
from order_data;

/*Q4 — Cancellation Rate
Calculate the overall order cancellation rate.
Return:
•	total_orders 
•	cancelled_orders 
•	cancellation_rate */
with order_data as(
	select count(*) as total_orders,
	sum(case when status='Cancelled' then 1 else 0 end) as cancelled_orders
    from orders
)
select total_orders, cancelled_orders,
(cancelled_orders/total_orders)*100 as cancellation_rate
from order_data;

/*Q5 — Revenue by Customer
Calculate the total completed-order revenue generated by each customer.
Return:
•	customer_id 
•	customer_name 
•	total_revenue 
Sort from highest to lowest revenue.*/

with customer_data as(
	select c.customer_id,c.customer_name,
    sum(case when o.status='Completed' then o.amount else 0 end) as completed_rev
    from customers c inner join orders o 
    on c.customer_id=o.customer_id
    group by c.customer_id,c.customer_name
)
select * from customer_data 
order by completed_rev desc;


/*Q6 — Customers Above Average Revenue
Find customers whose total completed-order revenue is greater than the average customer revenue.
Return:
•	customer_id 
•	customer_name 
•	total_revenue 
This requires comparing customer-level aggregation with an overall average*/

with customer_data as(
	select c.customer_id,c.customer_name, 
    sum(case when o.status='Completed' then o.amount else 0 end) as completed_rev
    from customers c inner join orders o 
    on c.customer_id=o.customer_id
    group by c.customer_id,c.customer_name
),
benchmark as(
	select avg(completed_rev) as overall_avg_rev
    from customer_data
       
)    
select * from customer_data cd
cross join benchmark b
where cd.completed_rev>b.overall_avg_rev;

/*Q7 — Category Revenue
Calculate completed-order revenue for each product category.
Return:
•	category 
•	total_revenue 
Sort from highest to lowest revenue.*/

SELECT
    p.category,
    SUM(
        CASE
            WHEN o.status = 'Completed' THEN o.amount
            ELSE 0
        END
    ) AS total_revenue
FROM products p
INNER JOIN orders o
    ON p.product_id = o.product_id
GROUP BY p.category
ORDER BY total_revenue DESC;

/*Q8 — Revenue Contribution %
Calculate each product category's percentage contribution to total completed revenue.
Return:
•	category 
•	total_revenue 
•	revenue_contribution_pct */

with prod_data as(
select category,
	sum(case when o.status='Completed' then o.amount else 0 end) as total_revenue
    FROM products p
	INNER JOIN orders o
    ON p.product_id = o.product_id
group by category
),
benchmark as(
	select sum(total_revenue) as overall_rev
    from prod_data
)
select *,
pd.total_revenue/b.overall_rev*100 as rev_precent
from prod_data pd
cross join benchmark b;
    
/*Q9 — High-Value Customers
Find customers whose completed-order revenue is greater than ₹10,000.
Return:
•	customer_id 
•	customer_name 
•	total_revenue 
•	order_count 
Only completed orders should be considered.*/

with customer_data as (
	select c.customer_id,c.customer_name,
    sum(case when o.status='Completed' then o.amount else 0 end) as total_revenue,
    sum(case when o.status='Completed' then 1 else 0 end) as total_orders
    from customers c inner join orders o 
    on c.customer_id=o.customer_id
    group by c.customer_id,c.customer_name
)
select * from customer_data
where total_revenue>10000; 

/*Q10 — Business KPI Summary
Create one result row containing:
•	total_revenue 
•	total_orders 
•	completed_orders 
•	cancelled_orders 
•	aov 
•	cancellation_rate*/
with order_data as(
	select 
		sum(amount) as total_rev,
        count(*) as total_orders,
        sum(case when status='Completed' then 1 else 0 end) as completed_orders,
        sum(case when status='Cancelled' then 1 else 0 end) as cancelled_orders
        from orders
)
select *,
total_rev/total_orders*100 as AOV,
cancelled_orders/total_orders*100 as cancellation_rate
from order_data;
